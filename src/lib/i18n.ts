type TranslationKey = keyof (typeof translations)["en"];
type TranslationParams = Record<string, string | number>;

function resolveLanguage(value: string | null | undefined): Language {
  if (value === "sq" || value === "hr" || value === "de" || value === "en")
    return value;
  return "en";
}

const initialLanguage = browser
  ? resolveLanguage(localStorage.getItem(STORAGE_KEY))
  : "en";
export const language = writable<Language>(initialLanguage);

if (browser) {
  language.subscribe((value) => {
    localStorage.setItem(STORAGE_KEY, value);
  });
}

export const t = derived(language, ($language) => {
  return (key: TranslationKey, params?: TranslationParams) => {
    const template = translations[$language][key] || translations.en[key];
    if (!params) return template;
    return template.replace(/\{(\w+)\}/g, (_match, name: string) => {
      const value = params[name];
      return value === undefined ? "" : String(value);
    });
  };
});
